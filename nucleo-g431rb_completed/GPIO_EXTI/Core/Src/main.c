/**
  * @brief  GPIO 外部中断回调函数（重写 HAL 弱回调）
  * @param  GPIO_Pin: 触发中断的引脚号
  * @retval None
  */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  /* 判断是否为用户按键 B1（PC13）触发的中断 */
  if (GPIO_Pin == USER_BTN_Pin)
  {
    uint32_t now = HAL_GetTick();

    /* 去抖动：若距上次有效触发不足 DEBOUNCE_DELAY_MS 毫秒，则忽略本次中断 */
    if ((now - btn_debounce_tick) < DEBOUNCE_DELAY_MS)
    {
      return;
    }

    /* 更新去抖计时，触发有效按键响应 */
    btn_debounce_tick = now;
    HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
  }
}

